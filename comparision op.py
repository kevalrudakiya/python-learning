# Comparison operators in Python

print("Comparison Operators Example")
print("===========================")

print("10 == 10 ->", 10 == 10)
print("10 != 5 ->", 10 != 5)
print("10 > 5 ->", 10 > 5)
print("10 < 5 ->", 10 < 5)
print("10 >= 10 ->", 10 >= 10)
print("5 <= 10 ->", 5 <= 10)

