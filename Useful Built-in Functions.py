# abs () is cornvert to positive number
x = -50
print(abs(x))  # Output: 50

# max values
y = 10
z = 20
print(max(y, z))  # Output: 20
print(min(y, z))  # Output: 10
print(max(20 , 30 , 100, 50, 10))  # Output: 100
print(min(20 , 30 , 100, 50, 10))  # Output: 10

#pow () is used to calculate the power of a number
print(pow(5,6)) # Output: 15625 it means 5*5*5*5*5*5 = 15625

# round () is used to round a number to the nearest integer
print(round(1520.735456554,2)) # Output: 1521
print(round(1520.23)) # Output: 1520

#divmod () is used to return the quotient and remainder of a division operation as a tuple
print(divmod(10, 3)) # Output: (3, 1) it means 10/3 = 3 and remainder is 1
print(divmod(20, 7)) # Output: (2, 6) it means 20/7 = 2 and remainder is 6
print(divmod(15, 4)) # Output: (3, 3) it means 15/4 = 3 and remainder is 3
print(divmod(100, 10)) # Output: (10, 0) it means 100/10 = 10 and remainder is 0
print(divmod(25, 5)) # Output: (5, 0) it means 25/5 = 5 and remainder is 0


#sum () is used to return the sum of all items in an iterable
print(sum([20,55,22,19]))

#len () is used to return the number of items in an iterable
print(len([20,55,22,19])) # Output: 4
print(len('python')) # Output: 6        

#complex () is used to return the complex number
print(complex(2, 3)) # Output: (2+3j)

