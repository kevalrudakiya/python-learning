# bin() is used to convert an integer number to a binary string prefixed with “0b”.
print(bin(10)) # Output: 0b1010

#oct() is used to convert an integer number to an octal string prefixed with “0o”.
print(oct(10)) # Output: 0o12

#hex() is used to convert an integer number to a lowercase hexadecimal string prefixed with “0x”.
print(hex(10)) # Output: 0xa




